"""Generate Solidity replay vectors for DiscipleLedger from the integer mirror (intledger.py).
Each history is a list of ops; the Solidity test replays them and must match every final number bit for bit.
Run: python3 gen_ledger_vectors.py ../../contracts/test/bridge/"""
import random, sys
from fractions import Fraction as Fr
from intledger import Ledger, Q128

E18 = 10**18
# op codes: 0 settle(mark, tvl, distribute)  1 swap(dx, dy)  2 deposit(owner, dx, dy)  3 withdraw(id, s, b)
#           4 restake(id)  5 claim(id)  6 poke(id) (a checkpoint: it changes rounding, so it is replayed too)


def X(M):
    return int(Fr(M) * Q128)


def history(seed, steps=30):
    R = random.Random(seed)
    L = Ledger(1, 500 * E18, 500 * E18, X(1))
    L.creator_compounds = R.random() < 0.5
    tvl = R.choice([10**6, 20000, 8000]) * E18
    ops = []
    M = X(1)
    owners = {1: 1}

    def do(op, a=0, b=0, c=0):
        ops.append((op, a, b, c))
        if op == 0:
            L.settle(a, b, c == 1)
        elif op == 1:
            L.swap(a, b)
        elif op == 2:
            l, _, _ = L.deposit(a, b, c)
            pass
        elif op == 3:
            L.withdraw(a, b, c)
        elif op == 4:
            nl = L.restake(a)
            pass
        elif op == 5:
            L.claim(a)
        elif op == 6:
            return L.lot_view(a)

    for st in range(steps):
        do(0, M, tvl, 1)
        Mf = R.choice([Fr(1), Fr(6, 5), Fr(4, 5), Fr(3, 2), Fr(1, 2)])
        M = X(Mf)
        local = R.random() < 0.1
        do(0, M, tvl, 0 if local else 1)
        r = R.random()
        ids = list(L.lots)
        if r < 0.4:
            dx = R.randint(1, 60) * E18 * (1 if R.random() < .5 else -1)
            ex = Fr(R.randint(-3, 6), 1000) * abs(dx) * Mf
            dy = int(-dx * Mf + ex)
            if L.x + dx > E18 and L.y + dy > E18:
                do(1, dx, dy)
        elif r < 0.6:
            amt = R.randint(1, 300) * E18
            do(0, M, tvl, 1)
            do(2, 1000 + st, amt, int(amt * Mf * 2))
        elif r < 0.75:
            i = R.choice(ids)
            s, b, _ = do(6, i)
            s, b = s * R.choice([0, 1, 2]) // 2, b * R.choice([0, 1, 3]) // 3
            if s + b > 0 and L.Sp + L.B - s - b >= 10**7:
                do(0, M, tvl, 1)
                do(3, i, s, b)
        elif r < 0.85:
            i = R.choice(ids)
            if do(6, i)[1] > 0:
                do(0, M, tvl, 1)
                do(4, i)
        else:
            do(5, R.choice(ids))
    do(0, M, tvl, 1)
    lots = []
    for i in sorted(L.lots):
        s, b, c = L.lot_view(i)
        lots.append((s, b, c[0], c[1]))
    book = (L.x, L.y, L.Sp, L.B, L.I, L.escrow[0], L.escrow[1], L.creator_claim[0], L.creator_claim[1], L.L,
            1 if L.graduated else 0)
    return L.creator_compounds, ops, lots, book


def main(out):
    H = [history(s) for s in range(8)]
    L = ["// SPDX-License-Identifier: MIT", "pragma solidity 0.8.26;", "",
         "// GENERATED by sim/accounting/gen_ledger_vectors.py from the integer mirror intledger.py. Do not edit.", "",
         "library DiscipleLedgerVectors {",
         "    struct Op { uint8 op; int256 a; int256 b; int256 c; }",
         "    struct LotEnd { uint256 s; uint256 bal; uint256 claimX; uint256 claimY; }",
         "    struct History { bool creatorCompounds; Op[] ops; LotEnd[] lots; uint256[11] book; }", "",
         f"    function count() internal pure returns (uint256) {{ return {len(H)}; }}", "",
         "    function get(uint256 i) internal pure returns (History memory h) {"]
    for n, (cc, ops, lots, book) in enumerate(H):
        L.append(f"        if (i == {n}) {{")
        L.append(f"            h.creatorCompounds = {'true' if cc else 'false'};")
        L.append(f"            h.ops = new Op[]({len(ops)});")
        for j, (op, a, b, c) in enumerate(ops):
            L.append(f"            h.ops[{j}] = Op({op}, {a}, {b}, {c});")
        L.append(f"            h.lots = new LotEnd[]({len(lots)});")
        for j, t in enumerate(lots):
            L.append(f"            h.lots[{j}] = LotEnd({t[0]}, {t[1]}, {t[2]}, {t[3]});")
        L.append(f"            h.book = [uint256({book[0]}), " + ", ".join(str(v) for v in book[1:]) + "];")
        L.append("            return h;")
        L.append("        }")
    L += ["    }", "}", ""]
    open(out.rstrip("/") + "/DiscipleLedgerVectors.sol", "w").write("\n".join(L))
    print(len(H), "histories;", sum(len(h[1]) for h in H), "ops;", sum(1 for h in H if h[3][10]), "graduated;",
          sum(1 for h in H if h[0]), "with creator compounding")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "../../contracts/test/bridge/")
