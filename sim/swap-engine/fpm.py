"""Bit-exact Python port of Solady FixedPointMathLib.lnWad / expWad (MIT, commit 258f67cc)
plus a Decimal reference. Used to test the Solidity swap engine's integer algorithm offline."""
from decimal import Decimal, getcontext
getcontext().prec = 80
M256 = 1 << 256
LIM = 1 << 255

def _chk(v):
    assert -LIM <= v < LIM, "int256 overflow"
    return v

def tdiv(a, b):  # Solidity int division / sdiv: truncate toward zero
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b >= 0) else -q

def lnWad(x):
    assert x > 0, "LnWadUndefined"
    L = x.bit_length() - 1
    r = 255 - L
    x = ((x << r) % M256) >> 159
    p = (((((((((3273285459638523848632254066296 + x) * x) >> 96) + 24828157081833163892658089445524) * x) >> 96)
            + 43456485725739037958740375743393) * x) >> 96) - 11111509109440967052023855526967
    p = ((p * x) >> 96) - 45023709667254063763336534515857
    p = ((p * x) >> 96) - 14706773417378608786704636184526
    p = _chk(p * x - (795164235651350426258249787498 << 96))
    q = 5573035233440673466300451813936 + x
    q = 71694874799317883764090561454958 + ((x * q) >> 96)
    q = 283447036172924575727196451306956 + ((x * q) >> 96)
    q = 401686690394027663651624208769553 + ((x * q) >> 96)
    q = 204048457590392012362485061816622 + ((x * q) >> 96)
    q = 31853899698501571402653359427138 + ((x * q) >> 96)
    q = 909429971244387300277376558375 + ((x * q) >> 96)
    p = tdiv(p, q)
    p = _chk(1677202110996718588342820967067443963516166 * p)
    p = _chk(p + 16597577552685614221487285958193947469193820559219878177908093499208371 * (159 - r))
    p = _chk(p + 600920179829731861736702779321621459595472258049074101567377883020018308)
    return p >> 174

def expWad(x):
    if x <= -41446531673892822313:
        return 0
    assert x < 135305999368893231589, "ExpOverflow"
    x = tdiv(x << 78, 5 ** 18)
    k = (tdiv(x << 96, 54916777467707473351141471128) + 2 ** 95) >> 96
    x = x - k * 54916777467707473351141471128
    y = x + 1346386616545796478920950773328
    y = ((y * x) >> 96) + 57155421227552351082224309758442
    p = y + x - 94201549194550492254356042504812
    p = ((p * y) >> 96) + 28719021644029726153956944680412240
    p = _chk(p * x + (4385272521454847904659076985693276 << 96))
    q = x - 2855989394907223263936484059900
    q = ((q * x) >> 96) + 50020603652535783019961831881945
    q = ((q * x) >> 96) - 533845033583426703283633433725380
    q = ((q * x) >> 96) + 3604857256930695427073651918091429
    q = ((q * x) >> 96) - 14423608567350463180887372962807573
    q = ((q * x) >> 96) + 26449188498355588339934803723976023
    r = tdiv(p, q)
    assert r > 0
    return (r * 3822833074963236453042738258902158003155416615667 % M256) >> (195 - k)

D = Decimal
def ref_ln(x): return D(x) / D(10**18)
