"""Writes contracts/test/hook/libraries/DiscipleFlatMathVectors.sol: expected fills for the v0.2 flat curve from the
float sim (disciple-sim/v0/disciple_sim_lam.py, lam 0.05, band 1.0). The Solidity test checks them within 1e-9.
Run: python3 sim/swap-engine/gen_flat_vectors.py /mnt/project-files/disciple-sim/v0"""
import sys, random, os
sys.path.insert(0, sys.argv[1])
from disciple_sim_lam import Path, Pool

LAM, BAND = 0.05, 1.0
Q128 = 2 ** 128
rng = random.Random(20261108)
rows = []
while len(rows) < 120:
    u = 10 ** rng.uniform(18, 24)
    T = 10 ** rng.uniform(-4, 4)
    lean = rng.uniform(-1.6, 1.6)  # ln((v/u)/T): inside and outside the band
    v = u * T * pow(2.718281828459045, lean)
    k = rng.uniform(0.95, 1.06)
    fn = rng.randrange(4)
    buy = fn < 2
    usep = rng.random() < 0.5
    pth0 = Path(buy, T, k, 0.0, 0, 0, 1.0, None, LAM, BAND)
    r = v / u
    p = None
    if usep:
        m = pth0.raw(r)
        p = m * (1 + rng.uniform(0.0, 0.04)) if buy else m * (1 - rng.uniform(0.0, 0.04))
    pth = Path(buy, T, k, 0.0, 0, 0, 1.0, p, LAM, BAND)
    frac = 10 ** rng.uniform(-6, -0.3)
    try:
        if fn == 0:
            a = v * frac; exp = Pool.buy_in(pth, u, v, a)[0]
        elif fn == 1:
            a = u * frac; exp = Pool.buy_out(pth, u, v, a)[0]
        elif fn == 2:
            a = u * frac; exp = Pool.sell_in(pth, u, v, a)[0]
        else:
            a = v * frac * 0.9; exp = Pool.sell_out(pth, u, v, a)[0]
    except Exception:
        continue
    if not (exp > 1e6):
        continue
    rows.append((fn, int(u), int(v), int(k * 1e18), int(p * Q128) if p else 0, int(T * Q128), int(a), int(exp)))

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../contracts/test/hook/libraries/DiscipleFlatMathVectors.sol")
L = ["// SPDX-License-Identifier: MIT", "pragma solidity 0.8.26;", "",
     "// GENERATED by sim/swap-engine/gen_flat_vectors.py from the float sim (lam 0.05, band 1.0). Do not edit.", "",
     "library DiscipleFlatMathVectors {",
     "    struct V { uint8 fn; uint256 u; uint256 v; uint256 k; uint256 p; uint256 t; uint256 a; uint256 exp; }", "",
     f"    function n() internal pure returns (uint256) {{ return {len(rows)}; }}", "",
     "    function get(uint256 i) internal pure returns (V memory) {"]
for i, r in enumerate(rows):
    L.append(f"        if (i == {i}) return V({r[0]}, {r[1]}, {r[2]}, {r[3]}, {r[4]}, {r[5]}, {r[6]}, {r[7]});")
L += ["        revert();", "    }", "}", ""]
open(out, "w").write("\n".join(L))
print(len(rows), "vectors ->", out)
