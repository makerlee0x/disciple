"""Writes contracts/test/bridge/DiscipleSwapMathVectors.sol from the integer mirror (exact expected values)
and the 80-digit reference (pool-favour bounds). Run: python3 gen_vectors.py <repo>/contracts/test/bridge/"""
import sys, random, math
from engine import *
out_dir = sys.argv[1]
random.seed(20261103)
FN = {"buy_in": 0, "buy_out": 1, "sell_in": 2, "sell_out": 3}
F = {0: (buy_exact_in, ref_buy_exact_in, True), 1: (buy_exact_out, ref_buy_exact_out, False),
     2: (sell_exact_in, ref_sell_exact_in, True), 3: (sell_exact_out, ref_sell_exact_out, False)}
rows = []

def add(fn, u, v, k, p, amt, note):
    f, rf, is_out = F[fn]
    got = f(u, v, k, p, amt)
    ref = rf(u, v, k, p, amt)
    bound = int(ref) if is_out else -int(-ref // 1)   # floor for outputs, ceil for inputs
    assert (got <= bound) if is_out else (got >= bound), (note, got, ref)
    rows.append((fn, u, v, k, p, amt, got, bound, note))

def pool(usd_side, price, dc=18, dq=6):
    u = int(usd_side / price * 10**dc); v = int(usd_side * 10**dq)
    return u, v, mulDiv(v, Q128, u)

# Scenario A: $2.5k a side, coin $0.001 (18 dec), USDG 6 dec, 0.3% fee, anchor at seed, premium on/off
for prem_t, tag in ((10**6, "no premium"), (0, "fresh 4% premium"), (30, "premium 30s old")):
    u, v, T = pool(2500, 0.001)
    G = markup(premium(4 * 10**16, 30, prem_t), 3000)
    kb, ks = slopes(T, T, G)
    for usd in (0.01, 1, 77, 1000, 10000):
        add(0, u, v, kb, 0, int(usd * 1e6), f"A buy ${usd} in, {tag}")
        add(2, u, v, ks, 0, int(usd / 0.001 * 1e18), f"A sell ${usd} of coin, {tag}")
    for frac in (1e-9, 1e-3, 0.5, 0.9):
        add(1, u, v, kb, 0, int(u * frac), f"A buy {frac:g} of coin reserve exact out, {tag}")
        add(3, u, v, ks, 0, int(v * frac), f"A sell for {frac:g} of quote reserve exact out, {tag}")

# Scenario B: $5k a side, coin $2, both 18 dec, 0.3% fee. The source's quotes sit 1% outside the curve's own
# quotes (stale anchor), so the match boundary binds: fills start on the straight line and cross onto the curve.
def edges(u, v, kb, ks, d_ask, d_bid):
    r = mulDiv(v, Q128, u)
    return mulDiv(mulDiv(kb, r, WAD), 10**6 + d_ask, 10**6), mulDiv(mulDiv(ks, r, WAD), 10**6 - d_bid, 10**6)
u, v, T = pool(5000, 2.0, 18, 18)
for mv in (1.0, 1.02):
    pref = int(T * mv)
    kb, ks = slopes(pref, T, markup(WAD, 3000))
    pa, pb = edges(u, v, kb, ks, 10_000, 10_000)
    for usd in (0.5, 50, 500, 2000):
        add(0, u, v, kb, pa, int(usd * 1e18), f"B anchor x{mv} buy ${usd}, floor 1% above curve ask")
        add(2, u, v, ks, pb, int(usd / 2 * 1e18), f"B anchor x{mv} sell ${usd}, ceiling 1% below curve bid")
        add(1, u, v, kb, pa, int(usd / 2 * 1e18), f"B anchor x{mv} buy ${usd} exact out, floor binds")
        add(3, u, v, ks, pb, int(usd * 1e18), f"B anchor x{mv} sell for ${usd} exact out, ceiling binds")

# Scenario C: random states across decimals, imbalance and sizes
while len(rows) < 120:
    u = int(10 ** random.uniform(10, 28)); v = int(10 ** random.uniform(10, 28))
    T = mulDiv(v, Q128, u); pref = int(T * 10 ** random.uniform(-0.7, 0.7))
    G = markup(premium(4 * 10**16, 30, random.choice([0, 3, 30, 600])), random.choice([1000, 3000, 10000]))
    kb, ks = slopes(pref, T, G)
    pa, pb = edges(u, v, kb, ks, random.randint(-5000, 30000), random.randint(-5000, 30000)) if random.random() < .7 else (0, 0)
    fn = random.randrange(4); fr = 10 ** random.uniform(-10, -0.1)
    amt = {0: int(v * fr * 3), 1: int(u * fr), 2: int(u * fr * 3), 3: int(v * fr)}[fn] + 1
    k, p = (kb, pa) if fn < 2 else (ks, pb)
    try:
        add(fn, u, v, k, p, amt, "C random")
    except OverflowError:
        pass

# pricing-input vectors
prem = [(h, t, e, premium(h, t, e)) for h, t, e in
        [(4 * 10**16, 30, 0), (4 * 10**16, 30, 1), (4 * 10**16, 30, 7), (4 * 10**16, 30, 15), (4 * 10**16, 30, 29), (4 * 10**16, 30, 30), (4 * 10**16, 30, 10**6), (0, 30, 0)]]
mk = [(h, f, markup(h, f)) for h, f in [(WAD, 3000), (WAD, 0), (WAD + 4 * 10**16, 3000), (WAD, 10000), (WAD + 1, 1)]]

L = []
L.append("// SPDX-License-Identifier: MIT\npragma solidity 0.8.26;\n")
L.append("// GENERATED by sim/swap-engine/gen_vectors.py from the integer mirror (engine.py) and an 80-digit")
L.append("// Decimal reference. Do not edit by hand. `expected` must match bit for bit; `exactBound` is the exact")
L.append("// answer rounded toward the pool (floor for outputs, ceil for inputs).\n")
L.append("library DiscipleSwapMathVectors {")
L.append("    struct Fill { uint8 fn; uint256 u; uint256 v; uint256 k; uint256 p; uint256 amount; uint256 expected; uint256 exactBound; }")
L.append("    struct Prem { uint256 h0; uint256 tau; uint256 elapsed; uint256 expected; }")
L.append("    struct Mark { uint256 h; uint256 fee; uint256 expected; }\n")
L.append(f"    function fills() internal pure returns (Fill[] memory f) {{\n        f = new Fill[]({len(rows)});")
for i, (fn, u, v, k, p, a, g, b, note) in enumerate(rows):
    L.append(f"        f[{i}] = Fill({fn}, {u}, {v}, {k}, {p}, {a}, {g}, {b}); // {note}")
L.append("    }\n")
L.append(f"    function premiums() internal pure returns (Prem[] memory r) {{\n        r = new Prem[]({len(prem)});")
for i, t in enumerate(prem): L.append(f"        r[{i}] = Prem({t[0]}, {t[1]}, {t[2]}, {t[3]});")
L.append("    }\n")
L.append(f"    function markups() internal pure returns (Mark[] memory r) {{\n        r = new Mark[]({len(mk)});")
for i, t in enumerate(mk): L.append(f"        r[{i}] = Mark({t[0]}, {t[1]}, {t[2]});")
L.append("    }\n}\n")
open(out_dir.rstrip("/") + "/DiscipleSwapMathVectors.sol", "w").write("\n".join(L))
print(len(rows), "fill vectors;", sum(1 for r in rows if r[4]), "with a boundary")
