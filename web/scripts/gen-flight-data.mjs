// Generates the flight data block embedded in public/flight/engine.js and public/flight/replay.js from the
// TypeScript sources of truth: lib/flight/tiers.ts (tier ladder) and lib/rocketSkin.ts (SITE's rocket upgrades:
// SKINS / THRUSTERS / COINS). Usage: node scripts/gen-flight-data.mjs [--check]  (--check: exit 1 on drift)
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const rd=f=>fs.readFileSync(path.join(root,f),'utf8');
/** pull `export const NAME...= [ ... ];` array literal (plain object literals only) and evaluate it */
function arr(src,name,file){ const m=src.match(new RegExp(`export const ${name}\\b[^=]*=\\s*(\\[[\\s\\S]*?\\n\\]);`)); if(!m) throw new Error(`${name} not found in ${file}`);
  return (new Function(`return ${m[1]};`))(); }
const tiersSrc=rd('lib/flight/tiers.ts'), skinSrc=rd('lib/rocketSkin.ts');
const tiers=arr(tiersSrc,'FLIGHT_TIERS','tiers.ts');
const cos={ skins:arr(skinSrc,'SKINS','rocketSkin.ts'), thrusters:arr(skinSrc,'THRUSTERS','rocketSkin.ts'), coins:arr(skinSrc,'COINS','rocketSkin.ts') };
for(const t of tiers){ if(!(t.lo<t.hi)||!t.name||!t.bg||!t.sky) throw new Error('bad tier '+JSON.stringify(t)); }
const START='/* @gen:flight-data:start — GENERATED by scripts/gen-flight-data.mjs from lib/flight/tiers.ts + lib/rocketSkin.ts. Do not edit. */';
const END='/* @gen:flight-data:end */';
const block=[START,
  'const FLIGHT_TIERS='+JSON.stringify(tiers)+';',
  'const FLIGHT_COSMETICS='+JSON.stringify(cos)+';',
  END].join('\n');
let drift=false;
for(const f of ['public/flight/engine.js','public/flight/replay.js']){
  const s=rd(f), i=s.indexOf(START.slice(0,24)), j=s.indexOf(END); if(i<0||j<0) throw new Error('markers missing in '+f);
  const out=s.slice(0,i)+block+s.slice(j+END.length);
  if(out!==s){ drift=true; if(!process.argv.includes('--check')) fs.writeFileSync(path.join(root,f),out); }
}
if(process.argv.includes('--check')){ if(drift){ console.log('FAIL: flight data block out of date — run npm run gen:flight'); process.exit(1); } console.log(`PASS · ${tiers.length} tiers · ${cos.skins.length} skins · ${cos.thrusters.length} thrusters · ${cos.coins.length} coins in sync`); }
else console.log(drift?'updated engine.js / replay.js':'already up to date');
