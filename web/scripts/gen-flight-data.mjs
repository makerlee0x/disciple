// Generates the flight data block embedded in public/flight/engine.js and public/flight/replay.js from the
// TypeScript sources of truth: lib/flight/tiers.ts (tier ladder) and lib/rocketSkin.ts (SITE's rocket upgrades:
// SKINS / THRUSTERS / COINS). Usage: node scripts/gen-flight-data.mjs [--check]  (--check: exit 1 on drift)
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const rd=f=>fs.readFileSync(path.join(root,f),'utf8');
/** pull `export const NAME...= [ ... ];` array literal (plain object literals only) and evaluate it */
function arr(src,name,file){ const m=src.match(new RegExp(`export const ${name}\\b[^=]*=\\s*(\\[[\\s\\S]*?\\n\\]);`)); if(!m) throw new Error(`${name} not found in ${file}`);
  return (new Function(`return ${m[1]};`))(); }
const tiersSrc=rd('lib/flight/tiers.ts'), skinSrc=rd('lib/rocketSkin.ts');
const tiers=arr(tiersSrc,'FLIGHT_TIERS','tiers.ts');
const cos={ skins:arr(skinSrc,'SKINS','rocketSkin.ts'), thrusters:arr(skinSrc,'THRUSTERS','rocketSkin.ts'), coins:arr(skinSrc,'COINS','rocketSkin.ts') };
for(const t of tiers){ if(!(t.lo<t.hi)||!t.name||!t.bg||!t.sky) throw new Error('bad tier '+JSON.stringify(t)); }
const START='/* @gen:flight-data:start — GENERATED by scripts/gen-flight-data.mjs from lib/flight/tiers.ts + lib/rocketSkin.ts. Do not edit. */';
const END='/* @gen:flight-data:end */';
const block=[START,
  'const FLIGHT_TIERS='+JSON.stringify(tiers)+';',
  'const FLIGHT_COSMETICS='+JSON.stringify(cos)+';',
  END].join('\n');
let drift=false;
for(const f of ['public/flight/engine.js','public/flight/replay.js']){
  const s=rd(f), i=s.indexOf(START.slice(0,24)), j=s.indexOf(END); if(i<0||j<0) throw new Error('markers missing in '+f);
  const out=s.slice(0,i)+block+s.slice(j+END.length);
  if(out!==s){ drift=true; if(!process.argv.includes('--check')) fs.writeFileSync(path.join(root,f),out); }
}
// DISCIPLE icon set v1 (public/icons/v1/svg) → canvas draw specs embedded in engine.js only (Path2D works on the main
// thread and in the OffscreenCanvas worker; no image decode). Each icon = [[pathD, mode, strokeWidth, opacity], …],
// mode 's' stroke / 'f' fill, in the SVG's own viewBox units ([w,h] first).
const CANVAS_ICONS=['tramp','wall','rocket','crew','graduation','bomb-puff','bomb-grenade','bomb-bunker','bomb-cruise','bomb-nuke','bomb-atom',
  'meter-orbs-1','meter-orbs-2','meter-orbs-3','meter-orbs-4','meter-orbs-5','meter-orbs-6',
  'crown','star','gear'];
const n4=v=>+(+v).toFixed(3);
function svgSpec(name){ const src=rd(`public/icons/v1/svg/${name}.svg`), vb=src.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/), out=[[n4(vb[1]),n4(vb[2])]];
  const root=src.match(/<svg[^>]*>/)[0], rootSw=+(root.match(/stroke-width="([\d.]+)"/)||[0,1.5])[1];
  for(const m of src.matchAll(/<(path|circle|rect|line|ellipse|polyline|polygon)\b([^>]*?)\/?>/g)){ const [ ,tag,a]=m, at=k=>{ const r=a.match(new RegExp(`(?:^|\\s)${k}="([^"]*)"`)); return r?r[1]:null; };
    let d; if(tag==='path') d=at('d');
    else if(tag==='circle'){ const cx=+at('cx'),cy=+at('cy'),r=+at('r'); d=`M${n4(cx-r)} ${n4(cy)}a${r} ${r} 0 1 0 ${n4(2*r)} 0a${r} ${r} 0 1 0 ${n4(-2*r)} 0Z`; }
    else if(tag==='ellipse'){ const cx=+at('cx'),cy=+at('cy'),rx=+at('rx'),ry=+at('ry'); d=`M${n4(cx-rx)} ${n4(cy)}a${rx} ${ry} 0 1 0 ${n4(2*rx)} 0a${rx} ${ry} 0 1 0 ${n4(-2*rx)} 0Z`; }
    else if(tag==='rect'){ const x=+at('x')||0,y=+at('y')||0,w=+at('width'),h=+at('height'),r=Math.min(+(at('rx')||at('ry')||0),w/2,h/2);
      d=r?`M${n4(x+r)} ${n4(y)}h${n4(w-2*r)}a${r} ${r} 0 0 1 ${r} ${r}v${n4(h-2*r)}a${r} ${r} 0 0 1 ${-r} ${r}h${n4(-(w-2*r))}a${r} ${r} 0 0 1 ${-r} ${-r}v${n4(-(h-2*r))}a${r} ${r} 0 0 1 ${r} ${-r}Z`:`M${x} ${y}h${w}v${h}h${-w}Z`; }
    else if(tag==='line') d=`M${at('x1')} ${at('y1')}L${at('x2')} ${at('y2')}`;
    else { d='M'+at('points').trim().replace(/\s+/g,' L')+(tag==='polygon'?'Z':''); }
    const filled=at('fill')==='currentColor', stroked=at('stroke')!=='none';
    const sw=+(at('stroke-width')||rootSw), op=+(at('opacity')||1);
    if(filled) out.push([d,'f',0,op]); if(stroked&&!(filled&&at('stroke')==null&&false)) out.push([d,'s',sw,op]); }
  return out; }
const ICON_START='/* @gen:icons:start — GENERATED by scripts/gen-flight-data.mjs from public/icons/v1/svg (DISCIPLE icon set v1). Do not edit. */';
const ICON_END='/* @gen:icons:end */';
const iconBlock=[ICON_START,'const D_ICONS='+JSON.stringify(Object.fromEntries(CANVAS_ICONS.map(n=>[n,svgSpec(n)])))+';',ICON_END].join('\n');
{ const f='public/flight/engine.js', s=rd(f), i=s.indexOf(ICON_START.slice(0,18)), j=s.indexOf(ICON_END); if(i<0||j<0) throw new Error('icon markers missing in '+f);
  const out=s.slice(0,i)+iconBlock+s.slice(j+ICON_END.length);
  if(out!==s){ drift=true; if(!process.argv.includes('--check')) fs.writeFileSync(path.join(root,f),out); } }
if(process.argv.includes('--check')){ if(drift){ console.log('FAIL: flight data block out of date — run npm run gen:flight'); process.exit(1); } console.log(`PASS · ${tiers.length} tiers · ${cos.skins.length} skins · ${cos.thrusters.length} thrusters · ${cos.coins.length} coins in sync`); }
else console.log(drift?'updated engine.js / replay.js':'already up to date');
