// Generate typed ABI const exports (abitype-compatible, consumed by viem) from the
// DISCIPLE FLOW forge build. Usage: CONTRACTS_OUT=../contracts/out node scripts/gen-abi.mjs
import fs from "fs";
import path from "path";
const OUT = process.env.CONTRACTS_OUT || path.resolve("../contracts/out");
const NAMES = ["Launchpad", "BondingCurve", "QuoteProbe", "DiscipleHook", "DiscipleRouter", "TrampWallManager", "Token", "FeeRouter"];
const dir = path.resolve("lib/abi");
fs.mkdirSync(dir, { recursive: true });
const idx = [];
for (const n of NAMES) {
  const j = JSON.parse(fs.readFileSync(path.join(OUT, `${n}.sol`, `${n}.json`), "utf8"));
  const id = n[0].toLowerCase() + n.slice(1) + "Abi";
  fs.writeFileSync(path.join(dir, `${n}.ts`),
    `// AUTO-GENERATED by scripts/gen-abi.mjs from DISCIPLE FLOW contracts (contracts/ on main, testnet v2). Do not edit.\nexport const ${id} = ${JSON.stringify(j.abi, null, 2)} as const;\n`);
  idx.push(`export { ${id} } from "./${n}";`);
}
fs.writeFileSync(path.join(dir, "index.ts"), idx.join("\n") + "\n");
console.log("wrote", NAMES.length, "ABIs to", dir);
