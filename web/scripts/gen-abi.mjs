// Generate typed ABI const exports (abitype-compatible, consumed by viem).
// Prefer contracts/deployments/web-bundle/abi/*.json (FLOW postprocess); fall back to forge out.
// Usage:
//   node scripts/gen-abi.mjs
//   CONTRACTS_OUT=../contracts/out node scripts/gen-abi.mjs
import { execSync } from "child_process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "../..");
const BUNDLE_ABI = path.resolve(ROOT, "contracts/deployments/web-bundle/abi");
const FORGE_OUT = process.env.CONTRACTS_OUT || path.resolve(ROOT, "contracts/out");
const NAMES = [
  "Launchpad",
  "BondingCurve",
  "QuoteProbe",
  "DiscipleHook",
  "DiscipleRouter",
  "TrampWallManager",
  "Token",
  "FeeRouter",
  "MarketLens",
  "AnonLauncher",
];
const dir = path.resolve(__dirname, "../lib/abi");
fs.mkdirSync(dir, { recursive: true });

function loadAbi(name) {
  const bundlePath = path.join(BUNDLE_ABI, `${name}.json`);
  if (fs.existsSync(bundlePath)) {
    const j = JSON.parse(fs.readFileSync(bundlePath, "utf8"));
    return Array.isArray(j) ? j : j.abi;
  }
  const forgePath = path.join(FORGE_OUT, `${name}.sol`, `${name}.json`);
  const j = JSON.parse(fs.readFileSync(forgePath, "utf8"));
  return j.abi;
}

const idx = [];
// label the header with the last commit that touched the bundle ABIs (they track contracts/src, which can be ahead of
// what is deployed: see contracts/docs/redeploy-migration.md)
let bundleRev = "";
try { bundleRev = execSync("git log -1 --format=%h -- abi", { cwd: path.dirname(BUNDLE_ABI), encoding: "utf8" }).trim(); } catch { /* no git */ }
const source = fs.existsSync(BUNDLE_ABI)
  ? `contracts/deployments/web-bundle${bundleRev ? ` @ ${bundleRev}` : ""}`
  : "DISCIPLE FLOW forge out";
for (const n of NAMES) {
  const abi = loadAbi(n);
  const id = n[0].toLowerCase() + n.slice(1) + "Abi";
  fs.writeFileSync(
    path.join(dir, `${n}.ts`),
    `// AUTO-GENERATED by scripts/gen-abi.mjs from ${source}. Do not edit.\nexport const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  idx.push(`export { ${id} } from "./${n}";`);
}
fs.writeFileSync(path.join(dir, "index.ts"), idx.join("\n") + "\n");
console.log("wrote", NAMES.length, "ABIs to", dir, "from", source);
