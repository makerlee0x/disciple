// Generate typed ABI const exports (abitype-compatible, consumed by viem).
// Prefer contracts/deployments/web-bundle/abi/*.json (FLOW postprocess); fall back to forge out.
// Usage:
//   node scripts/gen-abi.mjs
//   CONTRACTS_OUT=../contracts/out node scripts/gen-abi.mjs
//   ABI_FROM_FORGE=FeeRouter,LockedLP ABI_ONLY=FeeRouter,LockedLP CONTRACTS_OUT=... node scripts/gen-abi.mjs
//     (ABI_FROM_FORGE: names read from the forge build even when the web-bundle exists, e.g. contracts on an
//      undeployed branch; ABI_ONLY: rewrite just these files, leaving hand-patched ones alone)
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "../..");
// WEB_BUNDLE_ABI: point at another checkout's bundle (e.g. main after a deploy PR) without copying contracts/.
const BUNDLE_ABI = process.env.WEB_BUNDLE_ABI ? path.resolve(process.env.WEB_BUNDLE_ABI) : path.resolve(ROOT, "contracts/deployments/web-bundle/abi");
const FORGE_OUT = process.env.CONTRACTS_OUT || path.resolve(ROOT, "contracts/out");
const NAMES = [
  "Launchpad",
  "BondingCurve",
  "QuoteProbe",
  "DiscipleHook",
  "DiscipleRouter",
  "TrampWallManager",
  "Token",
  "FeeRouter",
  "MarketLens",
  "AnonLauncher",
  // v4 (PR #97): PVE login gate, referral registry, USDG deposit escrow, quote pricer (keeper poke)
  "LoginGate",
  "ReferralRegistry",
  "UsdgDepositNotifier",
  "QuotePricer",
  // steep curve floor (#127): graduation floor bins (floorInfo / floorBands / FloorSeeded)
  "LockedLP",
];
const FROM_FORGE = new Set((process.env.ABI_FROM_FORGE || "").split(",").filter(Boolean));
const ONLY = new Set((process.env.ABI_ONLY || "").split(",").filter(Boolean));
const dir = path.resolve(__dirname, "../lib/abi");
fs.mkdirSync(dir, { recursive: true });

function loadAbi(name) {
  const bundlePath = path.join(BUNDLE_ABI, `${name}.json`);
  if (!FROM_FORGE.has(name) && fs.existsSync(bundlePath)) {
    const j = JSON.parse(fs.readFileSync(bundlePath, "utf8"));
    return Array.isArray(j) ? j : j.abi;
  }
  const forgePath = path.join(FORGE_OUT, `${name}.sol`, `${name}.json`);
  const j = JSON.parse(fs.readFileSync(forgePath, "utf8"));
  return j.abi;
}

const idx = [];
const source = fs.existsSync(BUNDLE_ABI)
  ? "contracts/deployments/web-bundle @ 22ec4c5f (RH testnet 46630 v5)"
  : "DISCIPLE FLOW forge out";
for (const n of NAMES) {
  const id = n[0].toLowerCase() + n.slice(1) + "Abi";
  idx.push(`export { ${id} } from "./${n}";`);
  if (ONLY.size && !ONLY.has(n)) continue;
  const abi = loadAbi(n);
  const src = FROM_FORGE.has(n) ? `DISCIPLE FLOW forge out (${process.env.ABI_FORGE_REF || "local build"})` : source;
  fs.writeFileSync(
    path.join(dir, `${n}.ts`),
    `// AUTO-GENERATED by scripts/gen-abi.mjs from ${src}. Do not edit.\nexport const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
}
fs.writeFileSync(path.join(dir, "index.ts"), idx.join("\n") + "\n");
console.log("wrote", NAMES.length, "ABIs to", dir, "from", source);
